import { createHash } from 'node:crypto'
import { constants } from 'node:fs'
import { access, mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'

const SCRIPT_DIR = import.meta.dirname
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..', '..')
const PROTOCOL_SNAPSHOT_NAME = 'adversarial-review@2026.7.31'
const OUTPUT_PATH = path.join(REPO_ROOT, 'src', 'shared', 'review', 'protocol-assets.ts')
const PIN_FILE_NAME = 'PIN.md'
const SCRIPT_RELATIVE_PATH = path.join('scripts', 'adversarial-review')

const UPSTREAM_PIN_VERSION = 'quirk-2026.7.31'
const UPSTREAM_SCRIPT_SHA256 = '886e59af7bda5f6741563788ee74d7b7e667f5a5eeea5555859aa6bcd8ea6ba5'
const UPSTREAM_SKILL_DIR_SHA256 = '2eaf811a335c9ce7b09167b83b339a9846f78dc6578da23f7a561b51cc5ee858'
const ORCA_REVIEW_PROTOCOL_VERSION = 'quirk-2026.7.31+orca.1'

const STAGE_PROMPT_ASSETS = {
  dirName: 'assets',
  constantSuffix: 'STAGE_PROMPT',
  exportName: 'REVIEW_STAGE_PROMPT_ASSETS',
  keyTypeName: 'ReviewStagePromptAssetKey'
}
const PROFILE_ASSETS = {
  dirName: 'profiles',
  constantSuffix: 'PROFILE',
  exportName: 'REVIEW_PROFILE_ASSETS',
  keyTypeName: 'ReviewProfileAssetKey'
}

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex')
}

async function listFilesRecursive(root) {
  const files = []
  async function walk(dir) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const entryPath = path.join(dir, entry.name)
      if (entry.isDirectory()) {
        await walk(entryPath)
      } else if (entry.isFile()) {
        files.push(entryPath)
      }
    }
  }
  await walk(root)
  return files
}

// Reproduces `find . -type f | sort | xargs cat | sha256sum` over the upstream
// tree: relative paths as POSIX `./`-prefixed strings, sorted by byte order,
// raw file bytes concatenated in that order. PIN.md is Orca-added provenance,
// not part of the upstream snapshot, so it is excluded here.
async function computeSkillDirHash(protocolDir) {
  const files = await listFilesRecursive(protocolDir)
  const relativePaths = files
    .map((filePath) => path.relative(protocolDir, filePath).split(path.sep).join('/'))
    .filter((relativePath) => relativePath !== PIN_FILE_NAME)
    .map((relativePath) => `./${relativePath}`)
    .sort((left, right) => Buffer.compare(Buffer.from(left), Buffer.from(right)))

  const chunks = []
  for (const relativePath of relativePaths) {
    const absolutePath = path.join(protocolDir, ...relativePath.slice(2).split('/'))
    chunks.push(await readFile(absolutePath))
  }
  return sha256(Buffer.concat(chunks))
}

async function readMarkdownAssets(dir) {
  const stems = (await readdir(dir, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
    .map((entry) => entry.name.slice(0, -3))
    .sort((left, right) => left.localeCompare(right, 'en'))

  const assets = []
  for (const stem of stems) {
    assets.push({ stem, markdown: await readFile(path.join(dir, `${stem}.md`), 'utf8') })
  }
  return assets
}

function constantName(suffix, stem) {
  return `${stem.replace(/-/g, '_').toUpperCase()}_${suffix}_MARKDOWN`
}

function serializeAssetGroup(group, assets) {
  const constants = assets
    .map(
      (asset) =>
        `// oxfmt-ignore\nconst ${constantName(group.constantSuffix, asset.stem)} = ${JSON.stringify(asset.markdown)}`
    )
    .join('\n\n')
  const keyType = `export type ${group.keyTypeName} = ${assets.map((asset) => JSON.stringify(asset.stem)).join(' | ')}`
  const entries = assets
    .map((asset) => `  ${JSON.stringify(asset.stem)}: ${constantName(group.constantSuffix, asset.stem)}`)
    .join(',\n')
  const record = `export const ${group.exportName}: Record<${group.keyTypeName}, string> = {\n${entries}\n}`
  return { constants, keyType, record }
}

function serializeEmbeddedModule(stagePromptAssets, profileAssets) {
  const stagePrompts = serializeAssetGroup(STAGE_PROMPT_ASSETS, stagePromptAssets)
  const profiles = serializeAssetGroup(PROFILE_ASSETS, profileAssets)

  return [
    '// Generated by config/scripts/generate-review-protocol-assets.mjs. Do not edit.',
    '',
    `export const UPSTREAM_PIN_VERSION = ${JSON.stringify(UPSTREAM_PIN_VERSION)}`,
    `export const UPSTREAM_SCRIPT_SHA256 = ${JSON.stringify(UPSTREAM_SCRIPT_SHA256)}`,
    `export const UPSTREAM_SKILL_DIR_SHA256 = ${JSON.stringify(UPSTREAM_SKILL_DIR_SHA256)}`,
    `export const ORCA_REVIEW_PROTOCOL_VERSION = ${JSON.stringify(ORCA_REVIEW_PROTOCOL_VERSION)}`,
    '',
    stagePrompts.constants,
    '',
    profiles.constants,
    '',
    stagePrompts.keyType,
    '',
    profiles.keyType,
    '',
    '// oxfmt-ignore',
    stagePrompts.record,
    '',
    '// oxfmt-ignore',
    profiles.record,
    ''
  ].join('\n')
}

async function buildArtifacts(repoRoot = REPO_ROOT) {
  const protocolDir = path.join(repoRoot, 'protocol', PROTOCOL_SNAPSHOT_NAME)
  const scriptPath = path.join(protocolDir, SCRIPT_RELATIVE_PATH)

  const scriptHash = sha256(await readFile(scriptPath))
  if (scriptHash !== UPSTREAM_SCRIPT_SHA256) {
    throw new Error(
      `Vendored script hash mismatch at ${path.relative(repoRoot, scriptPath)}: expected UPSTREAM_SCRIPT_SHA256 ${UPSTREAM_SCRIPT_SHA256}, found ${scriptHash}.`
    )
  }

  const dirHash = await computeSkillDirHash(protocolDir)
  if (dirHash !== UPSTREAM_SKILL_DIR_SHA256) {
    throw new Error(
      `Vendored directory hash mismatch at ${path.relative(repoRoot, protocolDir)}: expected UPSTREAM_SKILL_DIR_SHA256 ${UPSTREAM_SKILL_DIR_SHA256}, found ${dirHash}.`
    )
  }

  const stagePromptAssets = await readMarkdownAssets(path.join(protocolDir, STAGE_PROMPT_ASSETS.dirName))
  const profileAssets = await readMarkdownAssets(path.join(protocolDir, PROFILE_ASSETS.dirName))

  return [
    {
      path: path.join(repoRoot, 'src', 'shared', 'review', 'protocol-assets.ts'),
      content: serializeEmbeddedModule(stagePromptAssets, profileAssets)
    }
  ]
}

async function writeArtifacts(artifacts) {
  for (const artifact of artifacts) {
    await mkdir(path.dirname(artifact.path), { recursive: true })
    await writeFile(artifact.path, artifact.content, 'utf8')
  }
}

async function verifyArtifacts(artifacts, repoRoot = REPO_ROOT) {
  const stale = []
  for (const artifact of artifacts) {
    try {
      await access(artifact.path, constants.R_OK)
      if ((await readFile(artifact.path, 'utf8')) !== artifact.content) {
        stale.push(artifact.path)
      }
    } catch {
      stale.push(artifact.path)
    }
  }
  if (stale.length > 0) {
    throw new Error(
      `Generated review protocol assets are stale:\n${stale
        .map((filePath) => path.relative(repoRoot, filePath))
        .join('\n')}\nRun node config/scripts/generate-review-protocol-assets.mjs --write.`
    )
  }
}

async function main() {
  const artifacts = await buildArtifacts()
  await (process.argv.includes('--write') ? writeArtifacts : verifyArtifacts)(artifacts)
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error)
    process.exitCode = 1
  })
}

export {
  ORCA_REVIEW_PROTOCOL_VERSION,
  OUTPUT_PATH,
  UPSTREAM_PIN_VERSION,
  UPSTREAM_SCRIPT_SHA256,
  UPSTREAM_SKILL_DIR_SHA256,
  buildArtifacts,
  computeSkillDirHash,
  verifyArtifacts,
  writeArtifacts
}
